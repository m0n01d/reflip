// Regenerates src/BuildInfo.res before every real build (npm run build,
// npm run dev), so the page and the brain can both show what's actually
// deployed. Gitignored — this is a build artifact, not source, the same
// way dist/ and *.res.mjs are.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const git = (cmd, fallback) => {
  try {
    return execSync(cmd, { encoding: "utf8" }).trim();
  } catch {
    return fallback;
  }
};

const commitSha = git("git rev-parse --short HEAD", "unknown");
const dirty = git("git status --porcelain", "") !== "";
const builtAt = new Date().toISOString();

const source = `// Generated by scripts/write-build-info.mjs on every build. Do not edit
// by hand — regenerated each time, and gitignored like dist/ and *.res.mjs.
let commitSha = "${commitSha}"
let dirty = ${dirty}
let builtAt = "${builtAt}"
`;

writeFileSync(new URL("../src/BuildInfo.res", import.meta.url), source);
console.log(`BuildInfo: ${commitSha}${dirty ? "+dirty" : ""} at ${builtAt}`);
